"""
LLMRationaleLog — stores every rationale generated by the LLM with full context
snapshot, validation flags, and outcome linkage for the feedback loop.
"""
from __future__ import annotations

import json
from datetime import datetime
from typing import Optional
from uuid import uuid4

from sqlalchemy import Boolean, DateTime, Float, ForeignKey, Index, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column

from app.core.base import Base


class LLMRationaleLog(Base):
    __tablename__ = "llm_rationale_logs"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid4()))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)

    # Links (nullable — filled in progressively as the trade lifecycle advances)
    recommendation_id: Mapped[Optional[str]] = mapped_column(
        String(36), ForeignKey("recommendations.id", ondelete="SET NULL"), nullable=True, index=True
    )
    active_trade_id: Mapped[Optional[str]] = mapped_column(
        String(36), ForeignKey("active_trades.id", ondelete="SET NULL"), nullable=True, index=True
    )

    # Asset context
    asset_id: Mapped[str] = mapped_column(String(32), nullable=False)
    asset_category: Mapped[str] = mapped_column(String(32), nullable=False)
    direction: Mapped[str] = mapped_column(String(8), nullable=False)   # long | short
    horizon: Mapped[str] = mapped_column(String(8), nullable=False, default="near")  # near | far
    horizon_days: Mapped[int] = mapped_column(Integer, nullable=False, default=14)

    # LLM metadata
    provider_id: Mapped[str] = mapped_column(String(32), nullable=False)
    model: Mapped[str] = mapped_column(String(64), nullable=False)
    prompt_version: Mapped[str] = mapped_column(String(32), nullable=False, default="rationale_v1")

    # Input / Output
    context_snapshot: Mapped[str] = mapped_column(Text, nullable=False)   # JSON
    rationale_text: Mapped[str] = mapped_column(Text, nullable=False)

    # Validation
    validation_flags: Mapped[str] = mapped_column(Text, nullable=False, default="[]")   # JSON list of flag codes
    retry_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)

    # News cross-reference (populated shortly after generation)
    news_verified: Mapped[Optional[bool]] = mapped_column(Boolean, nullable=True)
    news_verification_detail: Mapped[Optional[str]] = mapped_column(Text, nullable=True)  # JSON

    # Market metrics verification (populated when ActiveTrade is created + at outcome)
    metrics_at_entry: Mapped[Optional[str]] = mapped_column(Text, nullable=True)   # JSON snapshot
    metrics_verification: Mapped[Optional[str]] = mapped_column(Text, nullable=True)  # JSON
    metrics_accuracy_score: Mapped[Optional[float]] = mapped_column(Float, nullable=True)  # 0-1

    # Outcome (copied from ActiveTrade when trade closes)
    outcome: Mapped[Optional[str]] = mapped_column(String(24), nullable=True)  # hit_tp | hit_sl | expired | manual
    outcome_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    closing_price: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    pnl_r: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

    # Scoring (computed at outcome time)
    quality_score: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)      # 0-10
    hallucination_rate: Mapped[Optional[float]] = mapped_column(Float, nullable=True)  # 0-1

    __table_args__ = (
        Index("ix_llm_rl_asset_direction", "asset_id", "direction", "outcome"),
        Index("ix_llm_rl_category_horizon", "asset_category", "horizon", "outcome"),
        Index("ix_llm_rl_provider", "provider_id", "model", "outcome"),
        Index("ix_llm_rl_created", "created_at"),
    )

    # ── helpers ──────────────────────────────────────────────────────────────

    def get_validation_flags(self) -> list[str]:
        try:
            return json.loads(self.validation_flags)
        except Exception:
            return []

    def set_validation_flags(self, flags: list[str]) -> None:
        self.validation_flags = json.dumps(flags)

    def get_context_snapshot(self) -> dict:
        try:
            return json.loads(self.context_snapshot)
        except Exception:
            return {}

    def get_metrics_at_entry(self) -> dict:
        try:
            return json.loads(self.metrics_at_entry) if self.metrics_at_entry else {}
        except Exception:
            return {}
